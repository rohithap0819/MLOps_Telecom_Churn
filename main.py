"""
main.py
=======

Purpose:
--------
Run the selected Telecom Churn model on current/batch data and perform
model monitoring.

IMPORTANT:
----------
Model training and model selection are NOT performed in this file.

The workflow is:

    model_selection.py
          |
          |-- selects best model using cross-validation
          |-- saves selected model as Joblib
          |-- saves model-selection metrics
          |-- logs selection results to MLflow
          |
          v
       main.py
          |
          |-- loads selected Joblib model
          |-- loads current.csv
          |-- validates current data
          |-- performs predictions
          |-- calculates monitoring metrics
          |-- logs metrics to MLflow
          |-- generates Evidently drift report
          |-- saves predictions

Usage:
------

Run on normal current data:

    python main.py

Run on stress/high-drift data:

    python main.py --batch stress

Run explicitly on current data:

    python main.py --batch current

Inputs:
-------
    data/train.csv
    data/current.csv
    data/current_stress.csv
    logs/model_selection_metrics.csv
    models/candidates/<selected_model>.joblib

Outputs:
--------
    logs/predictions_<batch>.csv
    logs/drift_report_<batch>.html
    MLflow run containing monitoring metrics

Educational project:
--------------------
This project is designed for learning MLOps concepts.
It is not intended to be a production deployment.
"""

# ============================================================
# 1. IMPORT LIBRARIES
# ============================================================

import argparse
from pathlib import Path

import joblib
import mlflow
import pandas as pd

from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
    roc_auc_score,
)

from evidently import Report
from evidently.presets import DataDriftPreset

from src.data.validate import validate_data


# ============================================================
# 2. PROJECT PATHS
# ============================================================

# ROOT_DIR points to the main project folder.
ROOT_DIR = Path(__file__).resolve().parent

# Training/reference dataset.
TRAIN_DATA_PATH = ROOT_DIR / "data" / "train.csv"

# Normal current/batch dataset.
CURRENT_DATA_PATH = ROOT_DIR / "data" / "current.csv"

# Optional stress dataset with higher drift.
STRESS_DATA_PATH = ROOT_DIR / "data" / "current_stress.csv"

# Model-selection results generated by model_selection.py.
MODEL_SELECTION_METRICS_PATH = (
    ROOT_DIR / "logs" / "model_selection_metrics.csv"
)

# Folder containing the selected Joblib model.
CANDIDATE_MODEL_DIR = ROOT_DIR / "models" / "candidates"

# Logs folder.
LOGS_DIR = ROOT_DIR / "logs"

# MLflow tracking directory.
MLFLOW_DIR = ROOT_DIR / "mlruns"


# ============================================================
# 3. CONFIGURATION
# ============================================================

TARGET_COLUMN = "churn"
ID_COLUMN = "customer_id"

MLFLOW_EXPERIMENT_NAME = "Telecom_Churn_MLOps_Monitoring"


# ============================================================
# 4. ARGUMENT PARSER
# ============================================================

def parse_arguments():
    """
    Parse command-line arguments.

    The user only chooses which current batch to monitor.

    There is intentionally NO --model argument.

    The model is automatically determined from the results of
    model_selection.py.
    """

    parser = argparse.ArgumentParser(
        description="Run selected Telecom Churn model on current data."
    )

    parser.add_argument(
        "--batch",
        choices=["current", "stress"],
        default="current",
        help=(
            "Choose the dataset to monitor. "
            "'current' uses current.csv. "
            "'stress' uses current_stress.csv."
        ),
    )

    return parser.parse_args()


# ============================================================
# 5. GET CURRENT DATA PATH
# ============================================================

def get_current_data_path(batch_name):
    """
    Return the appropriate current dataset based on the batch name.
    """

    if batch_name == "current":
        return CURRENT_DATA_PATH

    if batch_name == "stress":
        return STRESS_DATA_PATH

    raise ValueError(f"Unsupported batch name: {batch_name}")


# ============================================================
# 6. LOAD MODEL-SELECTION RESULTS
# ============================================================

def load_model_selection_results():
    """
    Load the model-selection results generated by model_selection.py.

    model_selection.py evaluates:

        Logistic Regression
        Decision Tree

    using cross-validation and stores the results in:

        logs/model_selection_metrics.csv

    The model with the highest mean F1 score is considered
    the selected model.
    """

    if not MODEL_SELECTION_METRICS_PATH.exists():
        raise FileNotFoundError(
            "\nModel-selection metrics file was not found:\n"
            f"{MODEL_SELECTION_METRICS_PATH}\n\n"
            "Run model_selection.py first."
        )

    metrics_df = pd.read_csv(MODEL_SELECTION_METRICS_PATH)

    if metrics_df.empty:
        raise ValueError(
            "model_selection_metrics.csv is empty."
        )

    if "f1_mean" not in metrics_df.columns:
        raise ValueError(
            "Column 'f1_mean' was not found in "
            "model_selection_metrics.csv."
        )

    # Sort models by mean F1 score.
    metrics_df = metrics_df.sort_values(
        by="f1_mean",
        ascending=False
    ).reset_index(drop=True)

    selected_row = metrics_df.iloc[0]

    return metrics_df, selected_row


# ============================================================
# 7. FIND SELECTED MODEL FILE
# ============================================================

def get_selected_model_path(selected_row):
    """
    Convert the selected model name into the Joblib filename
    created by model_selection.py.

    Example:

        Logistic Regression
                |
                v
        logistic_regression.joblib

        Decision Tree
                |
                v
        decision_tree.joblib
    """

    model_name = str(selected_row["model"])

    model_filename = (
        model_name.lower()
        .replace(" ", "_")
        + ".joblib"
    )

    model_path = CANDIDATE_MODEL_DIR / model_filename

    if not model_path.exists():
        raise FileNotFoundError(
            "\nSelected model file was not found:\n"
            f"{model_path}\n\n"
            "Run model_selection.py first so that the selected "
            "model is created."
        )

    return model_path


# ============================================================
# 8. LOAD SELECTED MODEL
# ============================================================

def load_selected_model():
    """
    Load the model selected by model_selection.py.

    Returns:
        model
        model_name
        model_selection_metrics
        model_path
    """

    metrics_df, selected_row = load_model_selection_results()

    model_name = str(selected_row["model"])

    selected_f1 = float(selected_row["f1_mean"])

    model_path = get_selected_model_path(selected_row)

    print("\n" + "=" * 60)
    print("SELECTED MODEL")
    print("=" * 60)

    print(f"Model              : {model_name}")
    print(f"Cross-val Mean F1  : {selected_f1:.4f}")
    print(f"Model file         : {model_path}")

    print("\nAll model-selection results:")

    display_columns = [
        column
        for column in [
            "model",
            "f1_mean",
            "precision_mean",
            "recall_mean",
            "roc_auc_mean",
        ]
        if column in metrics_df.columns
    ]

    print(metrics_df[display_columns].to_string(index=False))

    # Load the already-trained model.
    model = joblib.load(model_path)

    print("\nSelected model loaded successfully.")

    return (
        model,
        model_name,
        selected_f1,
        model_path,
    )


# ============================================================
# 9. LOAD DATA
# ============================================================

def load_data(batch_name):
    """
    Load the reference training data and the selected current batch.
    """

    current_path = get_current_data_path(batch_name)

    if not TRAIN_DATA_PATH.exists():
        raise FileNotFoundError(
            f"Training/reference data not found:\n{TRAIN_DATA_PATH}"
        )

    if not current_path.exists():
        raise FileNotFoundError(
            f"Current batch data not found:\n{current_path}"
        )

    train_df = pd.read_csv(TRAIN_DATA_PATH)
    current_df = pd.read_csv(current_path)

    print("\n" + "=" * 60)
    print("DATA LOADING")
    print("=" * 60)

    print(f"Reference data : {TRAIN_DATA_PATH}")
    print(f"Current data   : {current_path}")

    print(f"\nReference rows : {len(train_df)}")
    print(f"Current rows   : {len(current_df)}")

    return train_df, current_df, current_path


# ============================================================
# 10. VALIDATE DATA
# ============================================================

def validate_datasets(train_df, current_df):
    """
    Validate both reference and current datasets using the
    project's existing validation function.
    """

    print("\n" + "=" * 60)
    print("DATA VALIDATION")
    print("=" * 60)

    print("\nValidating reference training data...")

    validate_data(train_df)

    print("Reference data validation successful.")

    print("\nValidating current data...")

    validate_data(current_df)

    print("Current data validation successful.")


# ============================================================
# 11. PREPARE FEATURES
# ============================================================

def prepare_features(df):
    """
    Prepare features for model prediction.

    The target column 'churn' and identifier column 'customer_id'
    are removed before prediction.

    Returns:
        X -> model input features
        y -> target values
    """

    if TARGET_COLUMN not in df.columns:
        raise ValueError(
            f"Target column '{TARGET_COLUMN}' is missing."
        )

    y = df[TARGET_COLUMN].copy()

    # Remove columns that should not be sent to the model.
    columns_to_drop = [
        column
        for column in [
            TARGET_COLUMN,
            ID_COLUMN,
        ]
        if column in df.columns
    ]

    X = df.drop(columns=columns_to_drop)

    return X, y


# ============================================================
# 12. RUN PREDICTIONS
# ============================================================

def run_predictions(model, current_df):
    """
    Run the selected model on the current batch.

    No model training occurs here.
    """

    X_current, y_current = prepare_features(current_df)

    print("\n" + "=" * 60)
    print("MODEL INFERENCE")
    print("=" * 60)

    print(f"Rows sent to model : {len(X_current)}")
    print("Running predictions...")

    predictions = model.predict(X_current)

    # Both Logistic Regression and Decision Tree support
    # predict_proba().
    probabilities = model.predict_proba(X_current)[:, 1]

    print("Prediction completed successfully.")

    return X_current, y_current, predictions, probabilities


# ============================================================
# 13. CALCULATE MONITORING METRICS
# ============================================================

def calculate_metrics(y_true, predictions, probabilities):
    """
    Calculate classification metrics for the current batch.

    Because current.csv contains the actual churn labels,
    we can calculate actual performance metrics.

    These are CURRENT-BATCH metrics.

    They are different from the cross-validation metrics
    produced during model selection.
    """

    metrics = {
        "accuracy": accuracy_score(
            y_true,
            predictions
        ),

        "precision": precision_score(
            y_true,
            predictions,
            zero_division=0
        ),

        "recall": recall_score(
            y_true,
            predictions,
            zero_division=0
        ),

        "f1": f1_score(
            y_true,
            predictions,
            zero_division=0
        ),

        "roc_auc": roc_auc_score(
            y_true,
            probabilities
        ),
    }

    return metrics


# ============================================================
# 14. PRINT MONITORING METRICS
# ============================================================

def print_metrics(metrics):
    """
    Display current-batch model performance.
    """

    print("\n" + "=" * 60)
    print("CURRENT BATCH MODEL PERFORMANCE")
    print("=" * 60)

    print(f"Accuracy  : {metrics['accuracy']:.4f}")
    print(f"Precision : {metrics['precision']:.4f}")
    print(f"Recall    : {metrics['recall']:.4f}")
    print(f"F1 Score  : {metrics['f1']:.4f}")
    print(f"ROC-AUC   : {metrics['roc_auc']:.4f}")


# ============================================================
# 15. SAVE PREDICTIONS
# ============================================================

def save_predictions(
    current_df,
    predictions,
    probabilities,
    batch_name,
):
    """
    Save predictions for the current batch.

    The original customer information is retained so that
    the prediction output can be inspected later.
    """

    output_df = current_df.copy()

    output_df["predicted_churn"] = predictions
    output_df["churn_probability"] = probabilities

    output_path = (
        LOGS_DIR / f"predictions_{batch_name}.csv"
    )

    output_df.to_csv(
        output_path,
        index=False
    )

    print("\n" + "=" * 60)
    print("PREDICTIONS SAVED")
    print("=" * 60)

    print(f"Output file: {output_path}")

    return output_path


# ============================================================
# 16. CONFIGURE MLFLOW
# ============================================================

def configure_mlflow():
    """
    Configure MLflow to use the project's local mlruns directory.
    """

    LOGS_DIR.mkdir(
        parents=True,
        exist_ok=True
    )

    MLFLOW_DIR.mkdir(
        parents=True,
        exist_ok=True
    )

    tracking_uri = MLFLOW_DIR.as_uri()

    mlflow.set_tracking_uri(tracking_uri)

    mlflow.set_experiment(
        MLFLOW_EXPERIMENT_NAME
    )

    print("\n" + "=" * 60)
    print("MLFLOW")
    print("=" * 60)

    print(f"Tracking URI : {tracking_uri}")
    print(f"Experiment   : {MLFLOW_EXPERIMENT_NAME}")


# ============================================================
# 17. LOG MONITORING RESULTS TO MLFLOW
# ============================================================

def log_mlflow_results(
    model_name,
    selected_model_f1,
    batch_name,
    current_path,
    model_path,
    metrics,
    prediction_path,
):
    """
    Log the monitoring run to MLflow.

    MLflow records:

        Parameters:
            selected model
            batch name
            data source

        Metrics:
            current-batch accuracy
            current-batch precision
            current-batch recall
            current-batch F1
            current-batch ROC-AUC

        Artifacts:
            selected Joblib model
            prediction CSV
    """

    with mlflow.start_run(
        run_name=f"monitoring_{batch_name}"
    ):

        # ----------------------------------------------------
        # Log parameters
        # ----------------------------------------------------

        mlflow.log_param(
            "selected_model",
            model_name
        )

        mlflow.log_param(
            "batch",
            batch_name
        )

        mlflow.log_param(
            "current_data",
            str(current_path.name)
        )

        mlflow.log_param(
            "model_source",
            "model_selection.py"
        )

        # This is the model-selection CV F1.
        mlflow.log_metric(
            "selected_model_cv_f1",
            selected_model_f1
        )

        # ----------------------------------------------------
        # Log current-batch performance
        # ----------------------------------------------------

        mlflow.log_metric(
            "current_accuracy",
            metrics["accuracy"]
        )

        mlflow.log_metric(
            "current_precision",
            metrics["precision"]
        )

        mlflow.log_metric(
            "current_recall",
            metrics["recall"]
        )

        mlflow.log_metric(
            "current_f1",
            metrics["f1"]
        )

        mlflow.log_metric(
            "current_roc_auc",
            metrics["roc_auc"]
        )

        # ----------------------------------------------------
        # Log model artifact
        # ----------------------------------------------------

        if model_path.exists():
            mlflow.log_artifact(
                str(model_path),
                artifact_path="selected_model"
            )

        # ----------------------------------------------------
        # Log predictions
        # ----------------------------------------------------

        if prediction_path.exists():
            mlflow.log_artifact(
                str(prediction_path),
                artifact_path="predictions"
            )

        run_id = mlflow.active_run().info.run_id

        print("\n" + "=" * 60)
        print("MLFLOW RUN COMPLETED")
        print("=" * 60)

        print(f"Run ID : {run_id}")

        print("\nMetrics logged:")
        print(
            f"  current_accuracy  = {metrics['accuracy']:.4f}"
        )
        print(
            f"  current_precision = {metrics['precision']:.4f}"
        )
        print(
            f"  current_recall    = {metrics['recall']:.4f}"
        )
        print(
            f"  current_f1        = {metrics['f1']:.4f}"
        )
        print(
            f"  current_roc_auc   = {metrics['roc_auc']:.4f}"
        )

    return run_id


# ============================================================
# 18. RUN EVIDENTLY DATA DRIFT REPORT
# ============================================================

def run_drift_report(
    reference_df,
    current_df,
    batch_name,
):
    """
    Generate an Evidently data-drift report.

    Reference:
        train.csv

    Current:
        current.csv or current_stress.csv

    The target and customer identifier are removed because
    drift monitoring here focuses on model input features.
    """

    print("\n" + "=" * 60)
    print("EVIDENTLY DATA DRIFT MONITORING")
    print("=" * 60)

    reference = reference_df.copy()
    current = current_df.copy()

    # Remove target and ID columns from drift analysis.
    columns_to_drop = [
        column
        for column in [
            TARGET_COLUMN,
            ID_COLUMN,
        ]
        if column in reference.columns
    ]

    reference = reference.drop(
        columns=columns_to_drop
    )

    current = current.drop(
        columns=columns_to_drop
    )

    print(
        f"Reference feature rows : {len(reference)}"
    )

    print(
        f"Current feature rows   : {len(current)}"
    )

    print("\nGenerating Evidently report...")

    report = Report(
        metrics=[
            DataDriftPreset(
                num_method="kl_div",
                cat_method="kl_div",
            )
        ]
    )

    snapshot = report.run(
        current_data=current_df,
        reference_data=reference_df,
    )

    report_path = (
        LOGS_DIR / f"drift_report_{batch_name}.html"
    )

    snapshot.save_html(
        str(report_path)
    )

    print("\nEvidently report generated successfully.")

    print(f"Report: {report_path}")

    return report_path


# ============================================================
# 19. MAIN WORKFLOW
# ============================================================

def main():
    """
    Execute the complete monitoring workflow.

    Workflow:

        1. Read batch argument
        2. Load selected model
        3. Load reference/current data
        4. Validate data
        5. Run inference
        6. Calculate current-batch metrics
        7. Save predictions
        8. Log metrics to MLflow
        9. Generate Evidently drift report

    No model training occurs here.
    """

    args = parse_arguments()

    batch_name = args.batch

    print("\n")
    print("=" * 60)
    print("TELECOM CHURN - MODEL MONITORING")
    print("=" * 60)

    print(f"\nBatch selected: {batch_name}")

    # --------------------------------------------------------
    # STEP 1: Load selected model
    # --------------------------------------------------------

    (
        model,
        model_name,
        selected_model_f1,
        model_path,
    ) = load_selected_model()

    # --------------------------------------------------------
    # STEP 2: Load datasets
    # --------------------------------------------------------

    (
        train_df,
        current_df,
        current_path,
    ) = load_data(batch_name)

    # --------------------------------------------------------
    # STEP 3: Validate datasets
    # --------------------------------------------------------

    validate_datasets(
        train_df,
        current_df
    )

    # --------------------------------------------------------
    # STEP 4: Run model inference
    # --------------------------------------------------------

    (
        X_current,
        y_current,
        predictions,
        probabilities,
    ) = run_predictions(
        model,
        current_df
    )

    # --------------------------------------------------------
    # STEP 5: Calculate current-batch metrics
    # --------------------------------------------------------

    metrics = calculate_metrics(
        y_current,
        predictions,
        probabilities
    )

    # --------------------------------------------------------
    # STEP 6: Display metrics
    # --------------------------------------------------------

    print_metrics(metrics)

    # --------------------------------------------------------
    # STEP 7: Save predictions
    # --------------------------------------------------------

    prediction_path = save_predictions(
        current_df,
        predictions,
        probabilities,
        batch_name,
    )

    # --------------------------------------------------------
    # STEP 8: Configure MLflow
    # --------------------------------------------------------

    configure_mlflow()

    # --------------------------------------------------------
    # STEP 9: Log monitoring results
    # --------------------------------------------------------

    run_id = log_mlflow_results(
        model_name=model_name,
        selected_model_f1=selected_model_f1,
        batch_name=batch_name,
        current_path=current_path,
        model_path=model_path,
        metrics=metrics,
        prediction_path=prediction_path,
    )

    # --------------------------------------------------------
    # STEP 10: Generate Evidently report
    # --------------------------------------------------------

    drift_report_path = run_drift_report(
        reference_df=train_df,
        current_df=current_df,
        batch_name=batch_name,
    )

    # --------------------------------------------------------
    # FINAL SUMMARY
    # --------------------------------------------------------

    print("\n")
    print("=" * 60)
    print("MONITORING WORKFLOW COMPLETED")
    print("=" * 60)

    print(f"\nSelected model       : {model_name}")

    print(
        f"Model-selection F1   : "
        f"{selected_model_f1:.4f}"
    )

    print(
        f"Current-batch F1     : "
        f"{metrics['f1']:.4f}"
    )

    print(
        f"Current-batch Recall : "
        f"{metrics['recall']:.4f}"
    )

    print(
        f"Current-batch ROC-AUC: "
        f"{metrics['roc_auc']:.4f}"
    )

    print(f"\nPredictions          : {prediction_path}")

    print(f"Evidently report     : {drift_report_path}")

    print(f"MLflow Run ID        : {run_id}")

    print("\n" + "=" * 60)



# ============================================================
# 20. SCRIPT ENTRY POINT
# ============================================================

if __name__ == "__main__":
    main()


