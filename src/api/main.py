# 3. Load production model
# --------------------------------------------------

def load_production_model():
    """
    Load the currently approved production model.

    The API should never silently use a candidate model.
    Only the model stored in the production directory
    is loaded for customer predictions.
    """

    # Check whether an approved production model exists.
    if not MODEL_PATH.exists():
        raise FileNotFoundError(
            "Production model not found. Approve a model first."
        )

    # joblib loads the saved scikit-learn model from disk.
    return joblib.load(MODEL_PATH)


def load_production_registry():
    """
    Load the production model registry.

    The registry stores metadata about the currently
    approved production model.
    """

    # If the registry does not exist yet, return an empty
    # dictionary instead of stopping the API.
    if not REGISTRY_PATH.exists():
        return {}

    # Open the JSON registry file and convert its contents
    # into a Python dictionary.
    with open(REGISTRY_PATH, "r", encoding="utf-8") as file:
        return json.load(file)


# --------------------------------------------------
# 4. Load initial model-selection metrics
# --------------------------------------------------

def load_initial_model_selection_metrics():
    """
    Load the metrics generated by model_selection.py.

    This is used during the INITIAL project stage,
    before any retraining has taken place.

    Returns:
        pandas.DataFrame:
            Model-selection results for the initial
            Logistic Regression and Decision Tree models.

    Raises:
        FileNotFoundError:
            If model_selection.py has not been executed yet.
    """

    # model_selection.py is expected to create this CSV.
    if not INITIAL_MODEL_SELECTION_PATH.exists():
        raise FileNotFoundError(
            "Initial model-selection metrics not found. "
            "Run model_selection.py first."
        )

    # Read the saved model comparison results.
    return pd.read_csv(INITIAL_MODEL_SELECTION_PATH)


# --------------------------------------------------
# 5. Load monitoring history
# --------------------------------------------------

def load_monitoring_history():
    """
    Load monitoring metrics generated by the monitoring workflow.

    This file is optional because monitoring history may not
    exist when the project is opened for the first time.

    Returns:
        pandas.DataFrame:
            Monitoring history if available.

        None:
            If monitoring history has not been generated yet.
    """

    # Monitoring history may not exist during the very first
    # execution of the project.
    if not MONITORING_HISTORY_PATH.exists():
        return None

    # Read the historical monitoring results.
    return pd.read_csv(MONITORING_HISTORY_PATH)


