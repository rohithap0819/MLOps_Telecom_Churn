# Human approval endpoint
# --------------------------------------------------

@app.post("/approval")
def approve_model(request: ApprovalRequest):
    """
    Process a human approval decision.

    There are two possible approval stages:

    1. Retraining approval
       A human decides whether retraining should start.

    2. Production approval
       After candidate models are trained, a human decides
       which candidate should become the production model.
    """

    try:

        # --------------------------------------------------
        # Check what type of approval is currently pending.
        #
        # There are two approval stages:
        #
        # 1. Retraining approval
        #    Drift was detected and human approval is required
        #    before candidate models can be trained.
        #
        # 2. Production approval
        #    Candidate models have already been trained and
        #    a human must choose which model goes to production.
        # --------------------------------------------------

        # Get the current pending approval request.
        pending_request = get_pending_approval()

        # There must be an approval request before a decision
        # can be submitted.
        if pending_request is None:
            raise ValueError(
                "There is no pending approval request."
            )

        # Read the approval type from the pending request.
        #
        # "retraining" means that candidate training has not
        # happened yet.
        #
        # "production" means candidate models have already
        # been trained and are waiting for production approval.
        #
        # If approval_type is missing, production is used as
        # the default for backward compatibility.
        approval_type = pending_request.get(
            "approval_type",
            "production"
        )

        # --------------------------------------------------
        # RETRAINING APPROVAL
        # --------------------------------------------------

        if approval_type == "retraining":

            # Send the human's decision to the approval module.
            #
            # request.decision might be something such as
            # "approve" or "reject".
            #
            # reviewer identifies the person making the decision.
            #
            # confirm_lower_f1 allows the workflow to explicitly
            # confirm a decision when the candidate F1 is lower.
            result = make_approval_decision(
                decision=request.decision,
                reviewer=request.reviewer,
                confirm_lower_f1=request.confirm_lower_f1
            )

            # If the human rejected retraining,
            # stop the workflow here.
            if result.get("status") == "retraining_rejected":
                return result

            # Candidate training is started only when the
            # retraining approval was successful.
            if result.get("status") == "retraining_approved":

                # Retrieve the training dataset that triggered
                # this retraining request.
                training_data_path = (
                    pending_request.get("training_data_path")
                )

                # The candidate-training function needs to know
                # which dataset should be used.
                if not training_data_path:
                    raise ValueError(
                        "Training data path is missing from "
                        "the retraining approval request."
                    )

                # Print useful information to the terminal so
                # learners can see that retraining has started.
                print("\n" + "=" * 60)
                print("RETRAINING APPROVED")
                print("=" * 60)

                print(
                    f"Training data : {training_data_path}"
                )

                print(
                    f"Reviewer      : {request.reviewer}"
                )

                print("Starting candidate training...")

                # --------------------------------------------------
                # Start candidate training only after human approval.
                # --------------------------------------------------

                # This function trains the candidate models.
                #
                # trigger_source tells the training process where
                # the retraining request came from, for example
                # Event Watcher or Scheduler.
                #
                # retraining_approved=True explicitly confirms that
                # the human approval step has already happened.
                training_result = run_candidate_training(
                    training_data_path=training_data_path,
                    trigger_source=pending_request.get(
                        "trigger_source",
                        "Unknown"
                    ),
                    retraining_approved=True
                )

                # --------------------------------------------------
                # Candidate training should create a new production
                # approval request after successful training.
                # --------------------------------------------------

                # If no training result was returned, training did
                # not produce new candidate results.
                if training_result is None:

                    return {
                        **result,
                        "message": (
                            "Retraining approved, but candidate "
                            "training did not produce new results."
                        )
                    }

                # Candidate training completed successfully.
                #
                # Notice that this does NOT automatically promote
                # the candidate to production.
                #
                # A separate production approval is now required.
                return {
                    **result,
                    "training_status": "completed",
                    "message": (
                        "Retraining approved and candidate "
                        "models trained successfully. "
                        "Production approval is now required."
                    )
                }

            # If the approval module returned another result,
            # return it to the API caller.
            return result

        # --------------------------------------------------
        # PRODUCTION APPROVAL
        # --------------------------------------------------

        # If the pending request is a production approval,
        # pass the human's decision to the approval module.
        #
        # At this stage the candidate models already exist,
        # and the human can decide which model should become
        # the production model.
        result = make_approval_decision(
            decision=request.decision,
            reviewer=request.reviewer,
            confirm_lower_f1=request.confirm_lower_f1
        )

        return result

    # ValueError represents an invalid approval request,
    # such as trying to approve when no request exists.
    except ValueError as error:

        raise HTTPException(
            status_code=400,
            detail=str(error)
        )

    # Required files are missing.
    except FileNotFoundError as error:

        raise HTTPException(
            status_code=404,
            detail=str(error)
        )

    # Catch any unexpected error.
    except Exception as error:

        raise HTTPException(
            status_code=500,
            detail=str(error)
        )


