@app.get("/pending-approval")
def pending_approval():
    """
    Return the currently pending human approval request.

    The dashboard uses this endpoint to determine whether
    a user needs to take an approval action.
    """

    # Ask the approval module whether an approval request exists.
    request = get_pending_approval()

    # If there is no pending request, return a clear response
    # instead of returning null.
    if request is None:
        return {
            "status": "no_pending_request",
            "message": "There are no pending approval requests."
        }

    # Return the complete pending approval request.
    return request


