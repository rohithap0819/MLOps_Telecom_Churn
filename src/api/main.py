@app.post("/predict", response_model=PredictionResponse)
def predict_churn(customer: CustomerData):
    """
    Predict whether a customer is likely to churn.

    The endpoint receives customer information, loads the
    approved production model, generates a prediction,
    and returns the churn probability.
    """

    try:

        # Load only the approved production model.
        #
        # Candidate models are not used for production predictions.
        model = load_production_model()

        # Convert the validated Pydantic request object into
        # a Pandas DataFrame.
        #
        # The model expects tabular input, so the single customer
        # is represented as one row.
        customer_data = pd.DataFrame(
            [customer.model_dump()]
        )

        # Generate the class prediction.
        #
        # The model returns an array, so [0] extracts the prediction
        # for our single customer.
        #
        # 0 = No Churn
        # 1 = Churn
        prediction = int(
            model.predict(customer_data)[0]
        )

        # predict_proba() returns the probability for each class.
        #
        # For binary classification:
        #
        # probabilities[0] -> probability of No Churn
        # probabilities[1] -> probability of Churn
        probabilities = model.predict_proba(
            customer_data
        )[0]

        # Extract the probability that this customer will churn.
        churn_probability = float(
            probabilities[1]
        )

        # Build the structured API response.
        return PredictionResponse(
            churn_prediction=prediction,

            # Convert the numeric prediction into a
            # human-readable label.
            churn_label=(
                "Churn"
                if prediction == 1
                else "No Churn"
            ),

            # Round the probability to four decimal places
            # to make the API response easier to read.
            churn_probability=round(
                churn_probability,
                4
            ),
        )

    # If the production model does not exist, the API cannot
    # generate predictions.
    #
    # HTTP 503 means the service is currently unavailable
    # for this operation.
    except FileNotFoundError as error:

        raise HTTPException(
            status_code=503,
            detail=str(error),
        )

    # Catch unexpected prediction errors.
    except Exception as error:

        raise HTTPException(
            status_code=500,
            detail=f"Prediction failed: {str(error)}",
        )


