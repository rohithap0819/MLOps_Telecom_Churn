@app.get("/model-comparison")
def model_comparison():
    """
    Return model-comparison information for the dashboard.

    This endpoint supports TWO stages of the MLOps project.

    INITIAL STAGE:
        model_selection.py
                |
                v
        model_selection_metrics.csv
                |
                v
        Dashboard

    RETRAINING STAGE:
        candidate_training.py
                |
                v
        candidate_metrics.csv
                |
                v
        Dashboard

    Candidate and production metrics are therefore optional
    during the initial project setup.
    """

    try:

        # --------------------------------------------------
        # INITIAL MODEL SELECTION
        # --------------------------------------------------

        # Load the results generated by model_selection.py.
        #
        # These results are available before any retraining
        # workflow has taken place.
        initial_metrics = load_initial_model_selection_metrics()

        # --------------------------------------------------
        # MONITORING HISTORY
        # --------------------------------------------------

        # Load monitoring results if they already exist.
        #
        # This is optional because a fresh project may not
        # have monitoring history yet.
        monitoring_history = load_monitoring_history()

        # --------------------------------------------------
        # RETRAINING / PRODUCTION METRICS
        # --------------------------------------------------

        # Candidate metrics are NOT required during the
        # initial project stage.
        #
        # They are created only after:
        #
        # New data
        #     ↓
        # Drift / policy
        #     ↓
        # Human retraining approval
        #     ↓
        # candidate_training.py
        #
        # Therefore, we only load them if they exist.
        try:
            candidate_metrics = load_candidate_metrics()

        except FileNotFoundError:
            # This is expected during the initial project stage.
            candidate_metrics = pd.DataFrame()

        # Production metrics are also optional during
        # initial project setup.
        try:
            production_metrics = load_production_metrics()

        except FileNotFoundError:
            # A production model may not exist yet.
            production_metrics = pd.DataFrame()

        # --------------------------------------------------
        # Convert DataFrames into JSON-compatible lists
        # --------------------------------------------------

        # FastAPI cannot directly return a Pandas DataFrame.
        #
        # to_json(orient="records") converts:
        #
        # DataFrame
        #     ↓
        # JSON records
        #
        # json.loads() then converts the JSON string into
        # normal Python objects that FastAPI can return.
        return {
            # Results from the INITIAL model-selection stage.
            "initial_model_selection": json.loads(
                initial_metrics.to_json(orient="records")
            ),

            # Monitoring results from main.py.
            #
            # Return an empty list if monitoring has not
            # produced any history yet.
            "monitoring": (
                json.loads(
                    monitoring_history.to_json(orient="records")
                )
                if monitoring_history is not None
                else []
            ),

            # Candidate metrics are empty during the
            # initial stage and populated after retraining.
            "candidates": json.loads(
                candidate_metrics.to_json(orient="records")
            ),

            # Production metrics are empty until a production
            # model has been approved.
            "production": json.loads(
                production_metrics.to_json(orient="records")
            ),
        }

    # If the INITIAL model-selection file does not exist,
    # model_selection.py needs to be executed first.
    except FileNotFoundError as error:

        raise HTTPException(
            status_code=404,
            detail=str(error)
        )

    # Catch unexpected errors and return HTTP 500.
    except Exception as error:

        raise HTTPException(
            status_code=500,
            detail=str(error)
        )


